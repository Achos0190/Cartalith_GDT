/// The capture calls \`_umRayBoxExit(dx,dy,UME.SITE_WM,UME.SITE_HM)\`, so the
/// box passed here is [\`SITE_WM\`]/[\`SITE_HM\`] and **not** the literals \`1700\`
/// / \`1250\`. That is the difference between a live and a dead assertion:
/// mutating \`SITE_HM\` to \`1251.0\` survived the whole matrix while these were
/// literals -- nothing else in the golden can see it, because
/// \`_umSiteBoxKm\` is \`max(SITE_WM,SITE_HM)/1000\` and the buildable-area
