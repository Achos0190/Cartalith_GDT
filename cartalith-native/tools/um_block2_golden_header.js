/* The Rust prelude `um_block2_capture.js` prints ahead of its captured data:
 * the doc header, the fixture rebuilt in Rust (`build_world`), the case
 * structs, and the assertions. Kept beside the capture rather than inside it
 * so the JS harness stays readable as a harness.
 *
 * `build_world` here MUST stay arithmetically identical to `heightMillis` /
 * `buildWorld` / `buildWays` in `um_block2_capture.js`. Both are integers with
 * one final `/1000`, so the two agree bit for bit; a change to either without
 * the other shows up immediately as every profile case failing at once.
 */
