"""AP-10 acceptance measurement (2026-10-19). Python 3.11 + numpy/scipy/Pillow.

Two modes, run in this order:

  py -3.11 -I ap10_measure.py make <src_dir> <fixture_dir>
      Writes the five 1024^2 sources (`src_<name>.png`): the research's four
      samples, regenerated by `../lineart-2026-10-18/lineart_lab.py`'s own
      functions and seeds (byte-identical to that lab's sources), plus
      `scan2`, a new pencil-on-cream scan of the hatched mountain with a fold
      crease, rotation, fibre texture, vignette, blur and JPEG q50. Also
      writes, per sample, the truth the Rust tests compare against:
      `truth_<name>_1024.png` (binary mask), `truth_<name>_40.png` (the
      1 px-floored target at x1, L8) and `truth_<name>.json` (component and
      hole counts of the floored target at each scale, and the un-floored
      truth's coverage sum, for ink mass).

  cargo run --release -p cartalith-assets --example lineart_frames -- <src_dir> <rust_dir>

  py -3.11 -I ap10_measure.py measure <src_dir> <rust_dir> <fig_dir>
      Scores the Rust renders against the truth with the lab's own `metrics`
      and `effective`, writes `results_ap10.json` and the figures.

The truth is the vector drawing, never the Rust output, so a Rust bug cannot
grade itself. Deterministic: fixed seeds, no timing in any figure.
"""
import io, json, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LAB_DIR = os.path.join(HERE, "..", "lineart-2026-10-18")
MODE = sys.argv[1] if len(sys.argv) > 1 else ""
# lineart_lab reads its output dir from argv[1] at import; give it a harmless one.
_argv = sys.argv
sys.argv = ["lineart_lab.py", os.environ.get("TEMP", ".")]
sys.path.insert(0, LAB_DIR)
import lineart_lab as lab  # noqa: E402
sys.argv = _argv

import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402
from scipy import ndimage as ndi  # noqa: E402

SCALES = lab.SCALES
SRC = lab.SRC


def rotate_strokes(strokes, fills, deg):
    """Rotate vector strokes about the sprite centre (the scan was fed in skewed)."""
    t = math.radians(deg)
    c, s = math.cos(t), math.sin(t)
    rot = lambda pts: [(0.5 + (x - 0.5) * c - (y - 0.5) * s, 0.5 + (x - 0.5) * s + (y - 0.5) * c) for x, y in pts]
    return [(rot(p), w) for p, w in strokes], [rot(p) for p in fills]


def make_scan2(strokes, fills, rng):
    """A pencil drawing on cream paper, scanned badly: graphite ink at 75 %
    density with pressure variation (strokes fade to 45 % in places), paper
    fibre (low-frequency +-4 %), grain (sigma 5), a vertical fold crease with
    its shadow and highlight, a 22 % vignette, a 0.7 px blur, JPEG q50."""
    cov = lab.render_truth(strokes, fills, SRC)
    pressure = ndi.gaussian_filter(rng.random((SRC, SRC)), 9)
    pressure = (pressure - pressure.min()) / (pressure.max() - pressure.min())
    cov = cov * np.clip(0.45 + 0.75 * pressure, 0, 1) * 0.75
    cov = ndi.gaussian_filter(cov, 0.7)
    yy, xx = np.mgrid[0:SRC, 0:SRC] / SRC
    fibre = ndi.gaussian_filter(rng.normal(0, 1, (SRC, SRC)), 20)
    fibre = 1 + 0.04 * fibre / np.abs(fibre).max()
    vignette = 1.0 - 0.22 * ((xx - 0.5) ** 2 + (yy - 0.5) ** 2) / 0.5
    crease = 1.0 - 0.18 * np.exp(-((xx - 0.62) / 0.012) ** 2) + 0.05 * np.exp(-((xx - 0.645) / 0.01) ** 2)
    paper = np.array([242, 236, 220], float)
    graphite = np.array([88, 88, 96], float)
    light = (vignette * fibre * crease)[..., None]
    img = paper[None, None] * light * (1 - cov[..., None]) + graphite[None, None] * light * cov[..., None]
    img += rng.normal(0, 5, img.shape)
    pil = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), "RGB")
    b = io.BytesIO()
    pil.save(b, "JPEG", quality=50)
    return np.asarray(Image.open(io.BytesIO(b.getvalue())).convert("RGB"), float)


def samples():
    """(name, strokes, fills, scan) for all five, with the lab's seeds."""
    out = []
    for si, (name, fn) in enumerate(lab.SAMPLES.items()):
        rng = np.random.default_rng(1000 + si)
        S, F = fn(rng)
        scan = lab.make_scan(name, S, F, np.random.default_rng(77 + si))
        out.append((name, S, F, scan))
    S, F = lab.mountain(np.random.default_rng(1000 + 2))
    S, F = rotate_strokes(S, F, 1.5)
    out.append(("scan2", S, F, make_scan2(S, F, np.random.default_rng(4242))))
    return out


def counts(b):
    st = np.ones((3, 3))
    return int(ndi.label(b, st)[1]), int(ndi.label(~b)[1] - 1)


def make(src_dir, fix_dir):
    os.makedirs(src_dir, exist_ok=True)
    os.makedirs(fix_dir, exist_ok=True)
    for name, S, F, scan in samples():
        Image.fromarray(scan.astype(np.uint8)).save(os.path.join(src_dir, f"src_{name}.png"), optimize=True)
        t1024 = lab.render_truth(S, F, SRC) > 0.5
        Image.fromarray((t1024 * 255).astype(np.uint8), "L").save(os.path.join(fix_dir, f"truth_{name}_1024.png"), optimize=True)
        t40 = lab.render_truth(S, F, 40, floor_px=1.0)
        Image.fromarray(np.round(t40 * 255).astype(np.uint8), "L").save(os.path.join(fix_dir, f"truth_{name}_40.png"))
        info = {}
        for H in SCALES:
            T = lab.render_truth(S, F, H, floor_px=1.0)
            comp, holes = counts(T > 0.5)
            info[str(H)] = {"comp_T": comp, "holes_T": holes, "raw_sum": float(lab.render_truth(S, F, H).sum())}
        info["truth_1024"] = {"comp": counts(t1024)[0], "holes": counts(t1024)[1]}
        json.dump(info, open(os.path.join(fix_dir, f"truth_{name}.json"), "w"), indent=1)
        print(name, json.dumps(info))


def load_a(path):
    return np.asarray(Image.open(path), float) / 255.0


def measure(src_dir, rust_dir, fig_dir):
    os.makedirs(fig_dir, exist_ok=True)
    stats = {json.loads(l)["name"]: json.loads(l) for l in open(os.path.join(rust_dir, "stats.jsonl"))}
    res = {}
    for name, S, F, scan in samples():
        row = {"rust_stats": stats.get(name)}
        frames = {"today": {}, "ap10": {}}
        for H in SCALES:
            T = lab.render_truth(S, F, H, floor_px=1.0)
            Traw = lab.render_truth(S, F, H)
            a = load_a(os.path.join(rust_dir, f"{name}_a{H}.png"))
            ink = np.broadcast_to(lab.INK, (H, H, 3))
            comp_img, e, halo = lab.effective(ink, a)
            m = lab.metrics(e, T)
            m["halo"] = round(halo, 4)
            m["mass"] = round(float(e.sum() / max(Traw.sum(), 1e-9)), 2)
            rgb, la = lab.legacy(scan, H)
            limg, le, lhalo = lab.effective(np.asarray(rgb, float), la)
            lm = lab.metrics(le, T)
            lm["halo"] = round(lhalo, 4)
            lm["mass"] = round(float(le.sum() / max(Traw.sum(), 1e-9)), 2)
            row[str(H)] = {"ap10": m, "today": lm}
            frames["ap10"][H] = lab.crop(comp_img, focus_name(name), H)
            frames["today"][H] = lab.crop(limg, focus_name(name), H)
        # Bar (a), the cleaned mask's IoU against the 1024^2 truth, is asserted
        # by the Rust test on the mask itself (`tests/lineart_ap10.rs`), which
        # this script cannot see.
        res[name] = row
        grid(name, scan, frames, fig_dir)
        bake = np.asarray(Image.open(os.path.join(rust_dir, f"{name}_bake256.png")).convert("RGBA"), float)
        row["bake256"] = {"alpha_mean": round(float(bake[..., 3].mean() / 255), 4),
                          "rgb_values": sorted({tuple(int(v) for v in p[:3]) for p in bake.reshape(-1, 4) if p[3] > 0})[:4]}
    json.dump(res, open(os.path.join(fig_dir, "results_ap10.json"), "w"), indent=1, default=int)
    for name, row in res.items():
        print(name)
        for H in SCALES:
            m, l = row[str(H)]["ap10"], row[str(H)]["today"]
            print(f"  x{H // 40:<3d} ap10 comp {m['comp']}/{m['comp_T']} holes {m['holes']}/{m['holes_T']} solid {m['solidity']} "
                  f"w_p5 {m['w_p5']} edge {m['edge_px']} mass {m['mass']} halo {m['halo']}   | today comp {l['comp']} holes {l['holes']} "
                  f"solid {l['solidity']} edge {l['edge_px']} halo {l['halo']}")


def focus_name(name):
    return {"scan2": "mountain"}.get(name, name)


def grid(name, scan, frames, fig_dir):
    """Rows: today's chain, AP-10 (Rust). Columns: the source (scaled to 200),
    x1 (40 px shown 5x nearest), x4 (160 px, whole), and 200 px crops at x16
    and x64, all over the lab's map green."""
    cell = 200
    pad = 6
    W = pad + 5 * (cell + pad)
    H = pad + 2 * (cell + pad)
    out = Image.new("RGB", (W, H), (40, 40, 40))
    src = Image.fromarray(np.clip(scan, 0, 255).astype(np.uint8)).resize((cell, cell), Image.LANCZOS)
    for r, key in enumerate(("today", "ap10")):
        y = pad + r * (cell + pad)
        out.paste(src, (pad, y))
        x1 = Image.fromarray(frames[key][40]).resize((cell, cell), Image.NEAREST)
        out.paste(x1, (pad + (cell + pad), y))
        x4 = Image.fromarray(frames[key][160]).resize((cell, cell), Image.NEAREST)
        out.paste(x4, (pad + 2 * (cell + pad), y))
        out.paste(Image.fromarray(frames[key][640]), (pad + 3 * (cell + pad), y))
        out.paste(Image.fromarray(frames[key][2560]), (pad + 4 * (cell + pad), y))
    out.save(os.path.join(fig_dir, f"ap10_grid_{name}.png"))


if __name__ == "__main__":
    if MODE == "make" and len(sys.argv) == 4:
        make(sys.argv[2], sys.argv[3])
    elif MODE == "measure" and len(sys.argv) == 5:
        measure(sys.argv[2], sys.argv[3], sys.argv[4])
    else:
        print(__doc__)
        sys.exit(2)
