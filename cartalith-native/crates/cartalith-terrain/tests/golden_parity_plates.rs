#![allow(clippy::excessive_precision)]
//! Golden-parity test for `build_plates` (PARITY_TESTING.md). Reference HTML
//! lines 2740-2766. Small grids/plate counts so the O(lloyd * cells * plates)
//! brute-force Lloyd relaxation stays cheap for a test fixture -- real usage
//! runs at map resolution, same algorithm.

use cartalith_terrain::{build_plates, Plate, WorldStructure};

#[test]
fn build_plates_case_0() {
    let plates = build_plates(6, 5, 12345, 4, 0, false, None);
    let expected: Vec<Plate> = vec![
        Plate { x: 1.8405135869979858, y: 2.421027107629925, vx: 0.6358688250184059, vy: 0.018856738694012165, base: 0.7063623372116127 },
        Plate { x: 4.598378804046661, y: 4.984132196987048, vx: 0.6500449702143669, vy: -0.08013025298714638, base: -0.9756298837019131 },
        Plate { x: 5.8160621132701635, y: 3.138302640290931, vx: -0.5023486507125199, vy: -0.05331432167440653, base: 0.6872703166562133 },
        Plate { x: 5.1910492605529726, y: 3.232343114214018, vx: 0.5602990980260074, vy: 0.574639807920903, base: 0.8438120876788162 },
    ];
    assert_eq!(plates, expected);
}

