//! **EF-9.1** -- per-tile *importance*: how much a pyramid tile would gain
//! from being drawn one level deeper
//! (`ELEVATION_FIELD_ARCHITECTURE_RESEARCH.md` §8.3, milestone EF-9.1).
//!
//! This module decides **nothing about what is drawn**. It reads a world's
//! already-computed rasters, aggregates them over one tile's footprint, and
//! scores the tile with weights that were **fitted by measurement** against
//! the refinement gain EF-9.0 measured (`G_scr`, the on-screen RMS difference
//! between a tile and its parent's bilinear resample). EF-9.2 will turn a
//! score into a subdivision choice; EF-9.1 only supplies the score.
//!
//! # The four invariants this module is written against (§8.2)
//!
//! * **I1** -- importance changes *which level* and *when*, never the content
//!   of a tile at a given `(z, col, row)`. Nothing here synthesises a texel.
//! * **I2** -- importance never moves a river threshold. No hydrology
//!   constant is read or written here.
//! * It is a **pure addition**: no generation code calls it, no golden covers
//!   it, and no generated byte depends on it.
//!
//! # What is fitted, and what is deliberately not
//!
//! The *geometric* terms ([`FEATURE_NAMES`]) predict how much new structure a
//! deeper level adds; the harness `crates/cartalith-civ/tests/ef9_refinement_gain.rs`
//! fits them (see [`FITTED_WEIGHTS`] for the exact command, seeds and the
//! held-out score). **Settlement and road terms are not fitted**: EF-9.0
//! measured Spearman rho 0.015 (settlements) and 0.11 (way length) against
//! `G_scr`, i.e. they do not predict geometric gain, they express what the
//! owner cares about. They enter only as a [`PolicyInputs`] bias that raises
//! synthesis *order* (Q2's default) and is structurally unable to touch
//! [`Importance::score`]: it is a different type, returned by a different
//! function, and never added to anything.
//!
//! # Absent is not zero
//!
//! Every input is an `Option` (`MISTAKES.md`: *never encode "no value" as a
//! plausible value*). A world without `stream_order` (carve-rivers off) or
//! with an empty `boundary_type` / `volcanic_field` (a `Loaded` save lacks the
//! tectonic-substrate grids, `cartalith-godot`'s `CivData` doc) yields `None`
//! for those terms, [`importance`] reports them [`TermState::Missing`], and
//! the score is summed over the terms that *are* present. A missing term is
//! skipped; it is never scored as order 0 or as "no boundary here".
//! **Consequence the caller must respect:** scores from two worlds that use
//! different term sets are not comparable with each other; within one world
//! every tile sees the same term set, so ranking tiles of one world is sound.

use cartalith_spatial::FloatRegion;
use cartalith_terrain::analysis;

/// Number of fitted geometric inputs.
pub const N_FEATURES: usize = 8;

/// Names of the fitted inputs, in the order every array in this module uses
/// ([`TileImportanceInputs::as_array`], [`ImportanceWeights::terms`],
/// [`Importance::terms_used`]) and in the order of the first eight entries of
/// EF-9.0's harness `INPUTS` table. Settlement and way length are not here:
/// they are [`PolicyInputs`], not fitted terms.
pub const FEATURE_NAMES: [&str; N_FEATURES] = [
    "slope_mean",
    "slope_max",
    "abs_curv_mean",
    "abs_tpi_mean",
    "stream_order_max",
    "land_fraction",
    "boundary_fraction",
    "volcanic_max",
];

/// Landmark fine scale in km: `cartalith-civ`'s `landmark.rs::SCALE_FINE_KM`
/// (3.0), the radius EF-9.0 §8.3 names for the `|tpi|` input. Restated
/// because that constant is private there and `cartalith-engine` cannot
/// depend on `cartalith-civ`; EF-9.0's harness asserts nothing against it, so
/// a change over there would not be caught here -- it is a copied constant,
/// labelled as one.
const TPI_FINE_KM: f64 = 3.0;
/// `landmark.rs::SCALE_MIN_CELLS` / `SCALE_MAX_CELLS`: the cell-radius clamp it
/// applies to [`TPI_FINE_KM`]. Copied for the same reason.
const TPI_MIN_CELLS: i64 = 2;
/// See [`TPI_MIN_CELLS`].
const TPI_MAX_CELLS: i64 = 40;
/// Curvature smoothing passed to `analysis::curvature_at`: EF-9.0 §8.3's
/// `|curvature_at(smooth = 2)|`. The raw one-cell Laplacian "should not be
/// thresholded directly on a noisy field" (that function's own doc).
const CURVATURE_SMOOTH: i64 = 2;

// ------------------------------------------------------------------ inputs

/// One tile's inputs, every one an `Option`: `None` means **the world does not
/// carry that field**, never "the value is zero".
///
/// Field order is [`FEATURE_NAMES`]. Produced by [`tile_features`]; consumed by
/// [`importance`]. Must never be filled with a default of `0.0` for a field
/// the world lacks -- that is the exact defect `Option` is here to prevent.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct TileImportanceInputs {
    /// Mean of `analysis::slope` over the footprint's coarse cells.
    pub slope_mean: Option<f64>,
    /// Max of the same.
    pub slope_max: Option<f64>,
    /// Mean of `|analysis::curvature_at(.., smooth = 2)|`.
    pub abs_curv_mean: Option<f64>,
    /// Mean of `|analysis::tpi|` at the landmark fine radius.
    pub abs_tpi_mean: Option<f64>,
    /// Max `stream_order` over the footprint; `None` when the world has no
    /// stream order (never order 0).
    pub stream_order_max: Option<f64>,
    /// Fraction of footprint cells strictly above sea level.
    pub land_fraction: Option<f64>,
    /// Fraction of footprint cells whose `boundary_type != 0`; `None` when the
    /// world has no `boundary_type` (a `Loaded` save), never "no boundary".
    pub boundary_fraction: Option<f64>,
    /// Max `volcanic_field` over the footprint; `None` when absent.
    pub volcanic_max: Option<f64>,
}

impl TileImportanceInputs {
    /// The inputs as an array in [`FEATURE_NAMES`] order.
    #[must_use]
    pub fn as_array(&self) -> [Option<f64>; N_FEATURES] {
        [
            self.slope_mean,
            self.slope_max,
            self.abs_curv_mean,
            self.abs_tpi_mean,
            self.stream_order_max,
            self.land_fraction,
            self.boundary_fraction,
            self.volcanic_max,
        ]
    }

    /// Inverse of [`Self::as_array`].
    #[must_use]
    pub fn from_array(a: [Option<f64>; N_FEATURES]) -> Self {
        Self {
            slope_mean: a[0],
            slope_max: a[1],
            abs_curv_mean: a[2],
            abs_tpi_mean: a[3],
            stream_order_max: a[4],
            land_fraction: a[5],
            boundary_fraction: a[6],
            volcanic_max: a[7],
        }
    }
}

/// A world's rasters, prepared once so any number of tiles can be aggregated
/// cheaply. EF-9.4 will cache one of these per world.
///
/// Holds the coarse-grid derivatives (slope, `|curvature|`, `|tpi|`) and a land
/// mask computed from the field at construction, plus the three optional
/// world grids. It owns copies, so it does not borrow the world and a sculpt
/// does not mutate it behind the caller's back (EF-9.5 rebuilds it).
///
/// Must never be built from a grid whose length is not `gw * gh` and then used
/// as if that field were present: [`Self::build`] maps a wrong-length
/// optional grid to `None` instead.
pub struct WorldImportanceField {
    gw: usize,
    gh: usize,
    /// `1` where `field > sea`, else `0`.
    land: Vec<u8>,
    slope: Vec<f32>,
    abs_curv: Vec<f32>,
    abs_tpi: Vec<f32>,
    stream_order: Option<Vec<i16>>,
    boundary: Option<Vec<u8>>,
    volcanic: Option<Vec<f32>>,
}

impl WorldImportanceField {
    /// Builds the aggregation source from a world's rasters.
    ///
    /// * `field` is the `gw * gh` heightmap, `sea` its sea level, `world` and
    ///   `map_km` the wrap flag and map width (`WorldParams::world`,
    ///   `map_width_km`) that fix the TPI radius.
    /// * `stream_order`: `None` when the world has none, and also `None` when
    ///   its length is not `gw * gh`.
    /// * `boundary` / `volcanic`: an **empty slice or any slice not `gw * gh`
    ///   long maps to `None`** -- a `Loaded` save's empty `boundary_type` is
    ///   "not carried", not "no boundaries" (`MISTAKES.md`: never encode "no
    ///   value" as a plausible value).
    ///
    /// # Panics
    /// If `field.len() != gw * gh` (the derivative functions assert it).
    #[must_use]
    #[allow(clippy::too_many_arguments)]
    pub fn build(
        field: &[f32],
        gw: usize,
        gh: usize,
        sea: f64,
        world: bool,
        map_km: f64,
        stream_order: Option<&[i16]>,
        boundary: &[u8],
        volcanic: &[f32],
    ) -> Self {
        let n = gw * gh;
        assert_eq!(field.len(), n, "field must be gw * gh");
        let cell_km = map_km / gw as f64;
        let r_fine = ((TPI_FINE_KM / cell_km).round() as i64).clamp(TPI_MIN_CELLS, TPI_MAX_CELLS);
        let abs = |v: Vec<f32>| v.into_iter().map(f32::abs).collect::<Vec<_>>();
        Self {
            gw,
            gh,
            land: field.iter().map(|&v| u8::from(v as f64 > sea)).collect(),
            slope: analysis::slope(field, gw, gh),
            abs_curv: abs(analysis::curvature_at(field, gw, gh, CURVATURE_SMOOTH, world)),
            abs_tpi: abs(analysis::tpi(field, gw, gh, r_fine, world)),
            stream_order: stream_order.filter(|o| o.len() == n).map(<[i16]>::to_vec),
            boundary: (boundary.len() == n).then(|| boundary.to_vec()),
            volcanic: (volcanic.len() == n).then(|| volcanic.to_vec()),
        }
    }

    /// Builds from a [`crate::WorldState`] and the parameters it was generated
    /// with: the one place the three optional grids are read off a world, so
    /// "empty `Vec` from a `Loaded` save" is mapped to absent exactly once.
    ///
    /// Returns `None` if `state.field` is shorter than `p.gw * p.gh` (the
    /// derivative functions would otherwise assert), or the grid is smaller
    /// than 2 in an axis.
    #[must_use]
    pub fn from_world(state: &crate::WorldState, p: &crate::WorldParams) -> Option<Self> {
        let n = p.gw.checked_mul(p.gh)?;
        if p.gw < 2 || p.gh < 2 || state.field.len() != n {
            return None;
        }
        Some(Self::build(
            &state.field,
            p.gw,
            p.gh,
            state.sea_level,
            p.world,
            p.map_width_km,
            state.stream_order.as_deref(),
            &state.boundary_type,
            &state.volcanic_field,
        ))
    }

    /// Coarse grid width.
    #[must_use]
    pub fn gw(&self) -> usize {
        self.gw
    }

    /// Coarse grid height.
    #[must_use]
    pub fn gh(&self) -> usize {
        self.gh
    }

    /// Whether the world carries a stream order. `false` means the term is
    /// absent for **every** tile.
    #[must_use]
    pub fn has_stream_order(&self) -> bool {
        self.stream_order.is_some()
    }

    /// Whether the world carries a `boundary_type` grid.
    #[must_use]
    pub fn has_boundary(&self) -> bool {
        self.boundary.is_some()
    }

    /// Whether the world carries a `volcanic_field` grid.
    #[must_use]
    pub fn has_volcanic(&self) -> bool {
        self.volcanic.is_some()
    }
}

/// Inclusive coarse-cell footprint `(x0, x1, y0, y1)` of a tile's bounds.
///
/// Cell `i` is the lattice square `[i, i + 1]` of the coarse sample space, so
/// the footprint is `floor(b.x) ..= ceil(b.x + b.w) - 1`: never empty (a tile
/// narrower than a cell still sees the cell it sits in) and clamped to the
/// grid. **Labelled judgement** (EF-9.0): the plan says "aggregated over the
/// footprint" without fixing the cell convention.
///
/// Moved here verbatim from EF-9.0's harness so importance and the harness
/// share one definition (EF-9.1 §8.3: "reusing EF-9.0's definitions").
/// `gw` and `gh` must be at least 1.
#[must_use]
pub fn footprint_cells(b: &FloatRegion, gw: usize, gh: usize) -> (usize, usize, usize, usize) {
    let axis = |lo: f64, len: f64, n: usize| {
        let a = (lo.floor().max(0.0) as usize).min(n - 1);
        let hi = ((lo + len).ceil() as i64 - 1).max(a as i64) as usize;
        (a, hi.min(n - 1))
    };
    let (x0, x1) = axis(b.x, b.w, gw);
    let (y0, y1) = axis(b.y, b.h, gh);
    (x0, x1, y0, y1)
}

/// **One tile's footprint aggregates** over `src` for a tile whose bounds in
/// coarse sample space are `bounds` (`cartalith_spatial::pyramid::pyramid_tile_bounds`).
///
/// The arithmetic is EF-9.0's, moved rather than restated: sums run
/// row-major over [`footprint_cells`], means divide by the cell count, the
/// stream-order and volcanic aggregates are maxima. An optional grid the world
/// does not carry gives `None` for its term; a present grid that happens to be
/// zero over the footprint gives `Some(0.0)` -- the two are different answers
/// and callers must keep them different.
#[must_use]
pub fn tile_features(src: &WorldImportanceField, bounds: &FloatRegion) -> TileImportanceInputs {
    let (x0, x1, y0, y1) = footprint_cells(bounds, src.gw, src.gh);
    let (mut sum_s, mut max_s, mut sum_c, mut sum_t) = (0.0f64, 0.0f64, 0.0f64, 0.0f64);
    let (mut land, mut bnd, mut max_o, mut max_v) = (0usize, 0usize, i16::MIN, f32::MIN);
    let mut cnt = 0usize;
    for y in y0..=y1 {
        for x in x0..=x1 {
            let i = y * src.gw + x;
            cnt += 1;
            sum_s += f64::from(src.slope[i]);
            max_s = max_s.max(f64::from(src.slope[i]));
            sum_c += f64::from(src.abs_curv[i]);
            sum_t += f64::from(src.abs_tpi[i]);
            land += usize::from(src.land[i]);
            if let Some(bt) = &src.boundary {
                bnd += usize::from(bt[i] != 0);
            }
            if let Some(o) = &src.stream_order {
                max_o = max_o.max(o[i]);
            }
            if let Some(v) = &src.volcanic {
                max_v = max_v.max(v[i]);
            }
        }
    }
    let c = cnt as f64;
    TileImportanceInputs {
        slope_mean: Some(sum_s / c),
        slope_max: Some(max_s),
        abs_curv_mean: Some(sum_c / c),
        abs_tpi_mean: Some(sum_t / c),
        stream_order_max: src.stream_order.is_some().then(|| f64::from(max_o)),
        land_fraction: Some(land as f64 / c),
        boundary_fraction: src.boundary.is_some().then(|| bnd as f64 / c),
        volcanic_max: src.volcanic.is_some().then(|| f64::from(max_v)),
    }
}

// ----------------------------------------------------------------- weights

/// One term of the fitted model: the standardisation constants and the weight.
///
/// `score += weight * (x - mean) / scale`. `mean` and `scale` are the training
/// tiles' mean and (population) standard deviation of the raw feature, so the
/// weights are comparable across terms. `weight = None` means the term was
/// **dropped** because its bootstrap 95 % interval included 0 (see
/// [`FITTED_WEIGHTS`]); a dropped term is not used and is not "missing" either
/// ([`TermState::Dropped`] vs [`TermState::Missing`]).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct FittedTerm {
    /// Training mean of the raw feature.
    pub mean: f64,
    /// Training standard deviation of the raw feature; must be `> 0`.
    pub scale: f64,
    /// Non-negative least-squares weight on the standardised feature, or
    /// `None` if the term was dropped.
    pub weight: Option<f64>,
}

/// A complete weight set: one [`FittedTerm`] per [`FEATURE_NAMES`] entry.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ImportanceWeights {
    /// In [`FEATURE_NAMES`] order.
    pub terms: [FittedTerm; N_FEATURES],
}

/// What happened to one term when a tile was scored.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TermState {
    /// The input was present and the term is in the model: it contributed.
    Used,
    /// The input is **absent** for this world: it did not contribute and was
    /// not scored as 0.
    Missing,
    /// The input was present but the model dropped the term (its fitted
    /// interval included 0): it did not contribute, by decision, not by
    /// absence.
    Dropped,
}

/// A tile's importance and which terms produced it.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Importance {
    /// Sum of `weight * z` over the [`TermState::Used`] terms; `None` when no
    /// term was used (every fitted term absent), never `0.0`.
    ///
    /// Higher = more refinement gain expected. Comparable only between tiles
    /// scored with the same `terms_used`.
    pub score: Option<f64>,
    /// Per-term outcome, in [`FEATURE_NAMES`] order.
    pub terms_used: [TermState; N_FEATURES],
}

impl Importance {
    /// Names of the terms reported [`TermState::Missing`].
    #[must_use]
    pub fn missing(&self) -> Vec<&'static str> {
        self.names_in(TermState::Missing)
    }

    /// Names of the terms that contributed.
    #[must_use]
    pub fn used(&self) -> Vec<&'static str> {
        self.names_in(TermState::Used)
    }

    fn names_in(&self, s: TermState) -> Vec<&'static str> {
        FEATURE_NAMES.iter().zip(&self.terms_used).filter(|&(_, &t)| t == s).map(|(&n, _)| n).collect()
    }
}

/// **Scores one tile.** Pure; deterministic.
///
/// For each term in `weights`: an absent input (`None`, or a non-finite
/// number, which is how an upstream `NaN` would arrive) is
/// [`TermState::Missing`] and contributes nothing; a present input with a
/// dropped term is [`TermState::Dropped`]; otherwise it adds
/// `weight * (x - mean) / scale`. Missing terms are *skipped*, not scored as 0
/// -- see the module header for what that means for comparing scores.
///
/// Must never read a settlement or a way: those are [`PolicyInputs`], and
/// importance has no argument through which they could enter.
#[must_use]
pub fn importance(features: &TileImportanceInputs, weights: &ImportanceWeights) -> Importance {
    let xs = features.as_array();
    let mut terms_used = [TermState::Missing; N_FEATURES];
    let mut score = 0.0f64;
    let mut any = false;
    for (k, term) in weights.terms.iter().enumerate() {
        match xs[k] {
            Some(x) if x.is_finite() => match term.weight {
                Some(w) => {
                    score += w * (x - term.mean) / term.scale;
                    terms_used[k] = TermState::Used;
                    any = true;
                }
                None => terms_used[k] = TermState::Dropped,
            },
            _ => {}
        }
    }
    Importance { score: any.then_some(score), terms_used }
}

// ---------------------------------------------------------- policy (Q2)

/// The human-significance inputs, **not fitted** (§8.3): plain numbers, because
/// settlements and ways are `cartalith-civ` types that `cartalith-engine`
/// cannot name. `None` = the world has no civ layer (or no ways), never a
/// count of zero.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct PolicyInputs {
    /// Settlements whose cell lies in the tile's footprint.
    pub settlement_count: Option<f64>,
    /// Way (road) length inside the footprint, in coarse-cell units.
    pub way_length: Option<f64>,
}

/// **Q2's policy bias** (§8.5, default): `Some(1)` if any *present* term is
/// positive, `Some(0)` if terms are present and all zero, `None` if both are
/// absent.
///
/// It is a *sort key prefix*, to be applied **within the level a tile already
/// has**: tiles with rank 1 are synthesised first. It is never added to
/// [`Importance::score`] and must never be compared with, thresholded
/// against, or used to promote a tile past its level -- EF-9.0 measured
/// settlements and ways as non-predictors of geometric gain (rho 0.015,
/// 0.11), so Q2's default is that they raise order only. A `None` rank means
/// "no information" and must be ordered as not-raised, never as 1.
#[must_use]
pub fn policy_rank(p: &PolicyInputs) -> Option<u8> {
    let present = [p.settlement_count, p.way_length];
    let mut any = false;
    for v in present.into_iter().flatten() {
        if !v.is_finite() {
            continue;
        }
        any = true;
        if v > 0.0 {
            return Some(1);
        }
    }
    any.then_some(0)
}

/// **Synthesis order within one level** (Q2): indices sorted by policy rank
/// first (rank 1 before rank 0 or `None`), then by importance score
/// descending (a `None` score last), then by index so the result is total and
/// deterministic.
///
/// This is the *only* place a [`policy_rank`] is consumed. It reorders tiles
/// that are all at the same level; it takes the scores by shared reference and
/// returns a permutation, so it cannot change a score, and nothing here maps a
/// rank to a level -- a policy-raised tile is synthesised *earlier*, never
/// *deeper*. `scores` and `ranks` must be the same length (a mismatch panics:
/// silently truncating would drop tiles from the schedule).
#[must_use]
pub fn synthesis_order(scores: &[Option<f64>], ranks: &[Option<u8>]) -> Vec<usize> {
    assert_eq!(scores.len(), ranks.len(), "one rank per score");
    let key = |i: usize| (ranks[i].unwrap_or(0), scores[i].filter(|v| v.is_finite()));
    let mut idx: Vec<usize> = (0..scores.len()).collect();
    idx.sort_by(|&a, &b| {
        let (ka, kb) = (key(a), key(b));
        kb.0.cmp(&ka.0).then_with(|| match (ka.1, kb.1) {
            (Some(x), Some(y)) => y.partial_cmp(&x).expect("finite"),
            (Some(_), None) => std::cmp::Ordering::Less,
            (None, Some(_)) => std::cmp::Ordering::Greater,
            (None, None) => std::cmp::Ordering::Equal,
        })
        .then(a.cmp(&b))
    });
    idx
}

