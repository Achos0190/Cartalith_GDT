    /// Protects: the tile -> footprint wiring against `pyramid_tile_bounds`:
    /// level 1 over an 8-cell grid is a 2x2 tiling, so tile (1, 0) must see
    /// cells `4..=7` by `0..=3`.
    #[test]
    fn tile_bounds_from_the_pyramid_pick_the_right_cells() {
        let mut order = vec![0i16; N * N];
        order[1 * N + 6] = 7; // inside tile (1, 0)
        order[1 * N + 1] = 9; // inside tile (0, 0)
        let src = WorldImportanceField::build(&vec![0.6f32; N * N], N, N, 0.42, false, 800.0, Some(&order), &[], &[]);
        let b10 = pyramid_tile_bounds(N, N, 1, 1, 0);
        assert_eq!(tile_features(&src, &b10).stream_order_max, Some(7.0));
        let b00 = pyramid_tile_bounds(N, N, 1, 0, 0);
        assert_eq!(tile_features(&src, &b00).stream_order_max, Some(9.0));
    }

    /// Protects: absent-is-not-zero at the source. A world with **no stream
    /// order** reports `stream_order_max` as `None`, and one whose stream order
    /// is present but all zero reports `Some(0.0)` -- two different answers.
    #[test]
    fn a_world_without_stream_order_reports_that_term_missing() {
        let field = field_with_sea_corner();
        let absent = WorldImportanceField::build(&field, N, N, 0.42, false, 800.0, None, &[], &[]);
        assert!(!absent.has_stream_order());
        let f = tile_features(&absent, &quad());
        assert_eq!(f.stream_order_max, None);
        let zeros = vec![0i16; N * N];
        let present = WorldImportanceField::build(&field, N, N, 0.42, false, 800.0, Some(&zeros), &[], &[]);
        assert!(present.has_stream_order());
        assert_eq!(tile_features(&present, &quad()).stream_order_max, Some(0.0));
        // and importance() carries the difference through: Missing vs Used.
        let w = local_weights();
        let mut w_all = w;
        w_all.terms[4].weight = Some(4.0); // make the term live so Missing vs Used is observable
        let a = importance(&f, &w_all);
        assert_eq!(a.terms_used[4], TermState::Missing);
        assert!(a.missing().contains(&"stream_order_max"));
        let b = importance(&tile_features(&present, &quad()), &w_all);
        assert_eq!(b.terms_used[4], TermState::Used);
        assert!(!b.missing().contains(&"stream_order_max"));
    }

    /// Protects: a `Loaded` save's empty `boundary_type` and `volcanic_field`
    /// reaching `from_world`: both terms must be missing -- not zero boundary,
    /// not zero volcanism -- while a world that carries the grids (even all
    /// zero) has them present. Also a wrong-length grid is absent, not
    /// truncated.
    #[test]
    fn a_loaded_world_with_empty_boundary_type_reports_those_terms_missing() {
        let p = crate::WorldParams::defaults(N, N, 1);
        let loaded = world(field_with_sea_corner(), Vec::new(), None, Vec::new());
        let src = WorldImportanceField::from_world(&loaded, &p).expect("field has gw*gh cells");
        assert!(!src.has_boundary() && !src.has_volcanic() && !src.has_stream_order());
        let f = tile_features(&src, &quad());
        assert_eq!((f.boundary_fraction, f.volcanic_max, f.stream_order_max), (None, None, None));
        assert!(f.slope_mean.is_some() && f.land_fraction.is_some(), "the field-derived terms stay present");
        let mut w = local_weights();
        w.terms[4].weight = Some(1.0);
        let imp = importance(&f, &w);
        assert_eq!(imp.missing(), vec!["stream_order_max", "boundary_fraction", "volcanic_max"]);
        // present-but-zero is a different, scored, answer
        let carried = world(field_with_sea_corner(), vec![0u8; N * N], Some(vec![0i16; N * N]), vec![0.0f32; N * N]);
        let src2 = WorldImportanceField::from_world(&carried, &p).unwrap();
        let f2 = tile_features(&src2, &quad());
        assert_eq!((f2.boundary_fraction, f2.volcanic_max, f2.stream_order_max), (Some(0.0), Some(0.0), Some(0.0)));
        assert!(importance(&f2, &w).missing().is_empty());
        // wrong length: absent
        let short = WorldImportanceField::build(&field_with_sea_corner(), N, N, 0.42, false, 800.0, Some(&[1i16; 3]), &[1u8; 5], &[0.5f32; 7]);
        assert!(!short.has_boundary() && !short.has_volcanic() && !short.has_stream_order());
        // a field that is not gw*gh yields no source at all
        let bad = world(vec![0.5; 10], Vec::new(), None, Vec::new());
        assert!(WorldImportanceField::from_world(&bad, &p).is_none());
    }

    /// Protects: `importance()` against hand arithmetic with the local weights:
    /// slope 5 -> 3*(5-1)/2 = 6, land 0.75 -> 1*(0.75-0.5)/0.25 = 1,
    /// boundary 0.0 (present) -> 2*(0-0.1)/0.1 = -2; stream order is a dropped
    /// term; everything else absent. Total 5.
    #[test]
    fn importance_is_the_standardised_weighted_sum_over_present_terms() {
        let x = TileImportanceInputs {
            slope_mean: Some(5.0),
            land_fraction: Some(0.75),
            boundary_fraction: Some(0.0),
            stream_order_max: Some(4.0),
            ..TileImportanceInputs::default()
        };
        let imp = importance(&x, &local_weights());
        assert!((imp.score.unwrap() - 5.0).abs() < 1e-12, "{:?}", imp.score);
        assert_eq!(imp.used(), vec!["slope_mean", "land_fraction", "boundary_fraction"]);
        assert_eq!(imp.terms_used[4], TermState::Dropped, "present but dropped is not Missing");
        assert_eq!(imp.missing(), vec!["slope_max", "abs_curv_mean", "abs_tpi_mean", "volcanic_max"]);
        // the three weights each matter: perturb one input at a time
        for (name, bump) in [("slope", 0usize), ("land", 5), ("boundary", 6)] {
            let mut a = x.as_array();
            *a[bump].as_mut().unwrap() += 0.5;
            let moved = importance(&TileImportanceInputs::from_array(a), &local_weights()).score.unwrap();
            assert!((moved - 5.0).abs() > 1e-9, "{name} must move the score");
        }
    }

    /// Protects: the never-score-absent-as-zero rule at the scoring step: a
    /// `NaN` or infinite input is `Missing` exactly like `None`; no usable term
    /// gives `score: None`, not `Some(0.0)`; and a missing term changes the
    /// score by *skipping*, not by contributing `weight * (0 - mean) / scale`.
    #[test]
    fn missing_terms_are_skipped_and_an_empty_score_is_none() {
        let w = local_weights();
        let none = importance(&TileImportanceInputs::default(), &w);
        assert_eq!(none.score, None);
        assert!(none.used().is_empty());
        let nan = importance(&TileImportanceInputs { slope_mean: Some(f64::NAN), land_fraction: Some(f64::INFINITY), ..Default::default() }, &w);
        assert_eq!(nan.score, None);
        assert_eq!(nan.terms_used[0], TermState::Missing);
        assert_eq!(nan.terms_used[5], TermState::Missing);
        // skipping: with only land present the score is land's term alone,
        // *not* land's plus what a zero slope would have contributed (-1.5).
        let only_land = importance(&TileImportanceInputs { land_fraction: Some(0.75), ..Default::default() }, &w);
        assert!((only_land.score.unwrap() - 1.0).abs() < 1e-12);
    }

    /// Protects: Q2's policy being a separate type with no path into the
    /// score. `policy_rank` is `Some(1)` for any present positive term,
    /// `Some(0)` for present-and-zero, `None` for absent (and a `NaN` does not
    /// count as present).
    #[test]
    fn policy_rank_distinguishes_positive_zero_and_absent() {
        let p = |s, w| PolicyInputs { settlement_count: s, way_length: w };
        assert_eq!(policy_rank(&p(Some(2.0), None)), Some(1));
        assert_eq!(policy_rank(&p(None, Some(0.5))), Some(1));
        assert_eq!(policy_rank(&p(Some(0.0), Some(0.0))), Some(0));
        assert_eq!(policy_rank(&p(Some(0.0), None)), Some(0));
        assert_eq!(policy_rank(&p(None, None)), None);
        assert_eq!(policy_rank(&p(Some(f64::NAN), None)), None);
        assert_eq!(policy_rank(&p(Some(f64::NAN), Some(0.0))), Some(0));
    }

    /// Protects: the policy raising *order* only. A rank-1 tile with a lower
    /// importance is synthesised before a rank-0 tile with a higher one; ties
    /// within a rank go by score, then by index; a `None` score sorts after
    /// every scored tile of its rank; and the scores slice is untouched (it is
    /// passed by shared reference and compared after).
    #[test]
    fn synthesis_order_raises_policy_tiles_first_and_never_alters_scores() {
        let scores = [Some(0.9), Some(0.1), None, Some(0.5), Some(0.5)];
        let ranks = [Some(0), Some(1), Some(1), None, Some(0)];
        let before = scores;
        let order = synthesis_order(&scores, &ranks);
        assert_eq!(order, vec![1, 2, 0, 3, 4], "rank 1 first (scored before unscored), then rank 0/None by score then index");
        assert_eq!(scores, before);
        // without policy the order is by score alone
        assert_eq!(synthesis_order(&scores, &[None; 5]), vec![0, 3, 4, 1, 2]);
    }

