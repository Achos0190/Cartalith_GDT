/// **The fitted weights** (EF-9.1). Every number below is *measured*, none is a
/// judgement; the run that produced it is reproducible with
///
/// ```text
/// cargo test --release -p cartalith-civ --test ef9_refinement_gain -- --ignored --nocapture ef9_1_importance_fit
/// ```
///
/// (seeds `483920, 24601, 71077345`; grids `2048x1311` and `512x384`; tile
/// 256 px; 3x3 windows of 16x16 tiles at z5..z10; about 5 minutes in release
/// plus the measurement). The weights that ship are the fit **trained on seeds
/// other than 71077345** (both grids, 55 295 tiles), so seed 71077345 -- the
/// last-listed seed, fixed before any result was seen -- is genuinely out of
/// sample for them.
///
/// * **Method.** Non-negative least squares of the standardised features
///   against `ln(G_scr)`, with a *within-(world, level)* fixed effect (x and y
///   centred per cell, which is also the free intercept) because importance
///   only ever ranks the tiles of one level of one world. `mean` / `scale` are
///   the training mean and population standard deviation each raw feature is
///   standardised with, so `weight` is in standard-deviation units.
///   `G_scr <= 0` tiles have no logarithm: they are excluded from the fit and
///   counted (1 of 55 296 in this training set), never floored to a small
///   number; they remain in held-out capture scoring.
/// * **Dropped terms** (`weight: None`): `abs_curv_mean`, `abs_tpi_mean` and
///   `stream_order_max` -- NNLS gave each an exact-zero point weight (their
///   information is already carried by slope), so they are dropped without a
///   bootstrap. Backward elimination on the 400-replicate tile bootstrap then
///   kept `slope_mean`, `slope_max`, `land_fraction` and `boundary_fraction`
///   (95 % intervals exclude 0) and `volcanic_max` (its interval's lower end is
///   0.0008, zero-share 0.022 < 0.025 -- **marginal**: the 1000-replicate
///   window-cluster bootstrap, a sensitivity check, would drop it).
/// * **What it buys, held out** (25 % budget, median over the (world, level)
///   cells, from the recorded run): leave-one-seed-out `0.579` against
///   `slope_mean` alone `0.576` (oracle `0.653`, centre-first `0.232`);
///   leave-one-grid-out `0.591` against `0.576`. The margin on the seed folds
///   is **0.003** -- the acceptance rule (fit >= `slope_mean` on both fold
///   families) is met, but it is a near tie there, and in 14 of 36 seed-fold
///   cells (12 of 36 grid-fold cells) the fit is below `slope_mean`. On the
