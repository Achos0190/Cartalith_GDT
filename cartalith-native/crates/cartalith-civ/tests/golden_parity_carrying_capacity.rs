#![allow(clippy::excessive_precision)]
//! Golden-parity tests for cartalith-civ's carrying capacity, NPP, and
//! population density (`buildCarryingCapacity`/`buildNPP`/
//! `estimateRegionalDensityKm2`, reference HTML lines 6238/6497/6217).
//! `PHASE2_SCOPE.md` milestone 4. Generated from a Node `vm` extraction
//! run against `reference/Cartalith Gen1 v2.10.html` (harness itself is
//! transient, not checked in) that calls the reference's own
//! `buildCarryingCapacity`/`buildNPP`/`estimateRegionalDensityKm2`
//! directly through `currentSoil()`/`currentWaterAccess()`/
//! `buildBiomeRaster()`, not a hand-composed reimplementation.
//!
//! Cases reuse `golden_parity_biome.rs`/`golden_parity_waterbodies.rs`'s
//! exact fixture configs (gw/gh/seed/world/w_iters=12). Cross-checked
//! before trusting this data: this harness's own `field[0..5]` matched
//! `cartalith-engine/tests/golden_parity_carve.rs`'s `expected_field[0..5]`
//! exactly for both cases (the same seeding fix milestone 2 required --
//! `state.tect.seed`, not `state.seed`), and the harness's determinism was
//! independently confirmed by running case 0 twice and diffing.
//!
//! All three fields are continuous (`Float32Array` in the reference) --
//! `1e-4` absolute+relative tolerance, matching this crate's own
//! `golden_parity_affordance.rs` convention.
//!
//! `biome_k=0.0`/`wet_mask=None` reproduces the reference's real default
//! (`_biomeK=0`, opts={} in the extraction) -- the biome-residual/wetland
//! correction path is ported but not exercised by these fixtures, same as
//! every other off-by-default toggle this port carries.

fn assert_close(actual: &[f32], expected: &[f32], label: &str) {
    const ATOL: f32 = 1e-4;
    const RTOL: f32 = 1e-4;
    assert_eq!(actual.len(), expected.len(), "{label}: length mismatch");
    for (i, (&a, &e)) in actual.iter().zip(expected.iter()).enumerate() {
        let tol = ATOL + RTOL * e.abs();
        assert!(
            (a - e).abs() <= tol,
            "{label} index {i}: got {a}, expected {e} (diff {}, tol {tol})",
            (a - e).abs()
        );
    }
}

