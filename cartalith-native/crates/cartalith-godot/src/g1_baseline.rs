/// One world's reading: the two column hashes, the FH-R2-shaped roster hash
/// (name, culture, religion, government, exactly as `fh_r2_baseline`
/// computes it) for bar 3, the faction count, how many real factions carry a
/// non-zero standing army (bar 1's guard against silently empty output) and
/// the rows themselves, indexed `faction - 1`.
struct Reading {
    governments: u64,
    roster_fh: u64,
    manpower: u64,
    factions: usize,
    armed: usize,
    rows: Vec<Manpower>,
}

/// The app's military chain over one generated world, read through
/// [`MilWorld`] (the body `WorldGen` runs), with `with_resources` as the
/// CIVIL ▸ Military path takes it unless a caller is checking that claim.
fn read(
    civ: &crate::CivData,
    ws: &cartalith_engine::WorldState,
    gh: usize,
    map_width_km: f64,
    seed: i32,
    with_resources: bool,
) -> Reading {
    let mw = MilWorld { civ, ws, gw: GW, gh, sea: ws.sea_level, map_width_km, seed };
    let view = CivView::live(civ);
    let defences = mw.defences_of(&civ.settlements, None);
    let agg = mw.aggregates_of(&view, &defences, with_resources);
    let rows: Vec<Manpower> =
        mw.manpower_rows_of(&view, &agg).into_iter().map(|r| r.manpower).collect();

    let mut g = Fnv::new();
    let mut r = Fnv::new();
    for e in civ.faction_roster.0.iter() {
        g.eat_str(&e.government);
        r.eat_str(&e.name);
        r.eat_str(&e.culture);
        r.eat_str(&e.religion);
        r.eat_str(&e.government);
    }
    let mut m = Fnv::new();
    for row in rows.iter() {
        for v in [
            row.standing_army,
            row.professional_core,
            row.emergency_mobilization,
            row.field_army,
            row.field_duration_days,
            row.emergency_duration_days,
            row.drivers.citizen_fraction,
        ] {
            m.eat(&v.to_bits().to_le_bytes());
        }
        m.eat_str(row.era_band.name);
        m.eat_str(row.era_standing_verdict);
        m.eat_str(row.era_mobilization_verdict);
    }
    Reading {
        governments: g.0,
        roster_fh: r.0,
        manpower: m.0,
        factions: civ.faction_roster.count(),
        armed: rows.iter().filter(|x| x.standing_army > 0.0).count(),
        rows,
    }
}

/// Every harness world, in [`G1_0`]'s order: `(seed, width_km, factions)`.
fn worlds() -> Vec<(i32, u32, i32)> {
    let mut v = Vec::new();
    for &seed in SEEDS.iter() {
        for &width in [800u32, 40_075].iter() {
            for &factions in [6i32, 24].iter() {
                v.push((seed, width, factions));
            }
        }
    }
    v
}

/// Protects G1-0's four bars (`GOVERNMENTS_SCOPE.md` §8) and, from G1-1 on,
/// the "0 of 20 worlds move" bar of every G1 stage:
///
/// 1. 20 of 20 worlds recorded, every column non-empty, at least 6 real
///    factions with a non-zero standing army on each world.
/// 2. Positive control: faction 1's government forced to `empire` (from its
///    default, `chiefdom`) moves the manpower column on at least 19 of 20
///    worlds and the governments column on 20 of 20; restored afterwards and
///    re-read, so the forcing cannot leak into the next world.
/// 3. The FH-R2-shaped roster hash equals `fh_r2_baseline::AT_CURRENT`'s on
///    all 20 worlds.
/// 4. (Runtime) printed for the caller to compare against `fh_r2_baseline`'s;
///    a timing is not asserted (`MISTAKES.md`: medians, run alone).
///
/// Then both columns are compared with [`G1_0`]. Ignored: it generates 20
/// worlds.
#[test]
#[ignore = "G1-0 measurement over 20 generated worlds; run alone with --ignored"]
fn g1_0_baseline_columns() {
    let t0 = std::time::Instant::now();
    let mut rows: Vec<G1Row> = Vec::new();
    let (mut moved_mp, mut moved_gov) = (0usize, 0usize);
    let mut roster_disagrees: Vec<String> = Vec::new();
    for (wi, &(seed, width, factions)) in worlds().iter().enumerate() {
        let (ws, mut civ, gh, p) = generate_world(seed, f64::from(width), factions, GW);
        let base = read(&civ, &ws, gh, p.map_width_km, seed, true);
        assert_eq!(base.factions, factions as usize, "seed {seed} {width} km");
        // `count()` is the real factions (index 0, Unclaimed, excluded), and
        // the chain reads one row per real faction.
        assert_eq!(base.rows.len(), factions as usize, "one manpower row per real faction");
        assert!(
            base.armed >= 6,
            "seed {seed} {width} km {factions}: only {} factions armed",
            base.armed
        );
        // Bar 3: the same roster `fh_r2_baseline` pins.
        let fh = AT_CURRENT[wi];
        assert_eq!((fh.0, fh.1, fh.2), (seed, width, factions), "world order");
        if base.roster_fh != fh.3 {
            roster_disagrees.push(format!("seed {seed} {width} km {factions}"));
        }
        // The resource-pass claim, checked once.
        if wi == 0 {
            let lean = read(&civ, &ws, gh, p.map_width_km, seed, false);
            assert_eq!(lean.manpower, base.manpower, "the resource passes moved a manpower figure");
        }
        // Bar 2: the positive control.
        let saved = civ.faction_roster.0[1].government.clone();
        assert_eq!(saved, "chiefdom", "faction 1's default government");
        civ.faction_roster.0[1].government = "empire".to_string();
        let forced = read(&civ, &ws, gh, p.map_width_km, seed, true);
        civ.faction_roster.0[1].government = saved;
        let back = read(&civ, &ws, gh, p.map_width_km, seed, true);
        assert_eq!((back.governments, back.manpower), (base.governments, base.manpower), "restore");
        moved_mp += usize::from(forced.manpower != base.manpower);
        moved_gov += usize::from(forced.governments != base.governments);

        println!(
            "G1 ({seed}, {width}, {factions}, 0x{:016x}, 0x{:016x}), // {} armed of {}; f1 standing {:.0} -> {:.0} under empire",
            base.governments,
            base.manpower,
            base.armed,
            factions,
            base.rows[0].standing_army,
            forced.rows[0].standing_army
        );
        rows.push((seed, width, factions, base.governments, base.manpower));
    }
    println!(
        "G1 positive control: manpower moved on {moved_mp} of 20, governments on {moved_gov} of 20; {:.1} s",
        t0.elapsed().as_secs_f64()
    );
    assert_eq!(rows.len(), 20);
    assert!(moved_mp >= 19, "positive control: manpower moved on only {moved_mp} of 20");
    assert_eq!(moved_gov, 20, "positive control: governments moved on {moved_gov} of 20");
    assert!(!G1_0.is_empty(), "G1_0 is not recorded yet: paste the G1 lines above");
    let moved: Vec<String> = rows
        .iter()
        .zip(G1_0.iter())
        .filter(|(g, w)| g != w)
        .map(|(g, w)| format!("got {g:?} want {w:?}"))
        .collect();
    let gov_moved = rows.iter().zip(G1_0.iter()).filter(|(g, w)| g.3 != w.3).count();
    let mp_moved = rows.iter().zip(G1_0.iter()).filter(|(g, w)| g.4 != w.4).count();
    println!(
        "G1 against G1_0: governments moved on {gov_moved} of 20, manpower on {mp_moved} of 20; roster disagrees with fh_r2_baseline on {} of 20",
        roster_disagrees.len()
    );
    assert!(roster_disagrees.is_empty(), "roster disagrees with fh_r2_baseline: {roster_disagrees:?}");
    assert!(moved.is_empty(), "G1: {} of 20 worlds moved:\n{}", moved.len(), moved.join("\n"));
}

