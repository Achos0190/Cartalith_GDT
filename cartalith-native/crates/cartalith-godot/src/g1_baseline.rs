/// G1-1's bar 4 (`GOVERNMENTS_SCOPE.md` §8): on every harness world, faction
/// 1 forced to each appended form in turn (then to that form's anchor row,
/// then restored). Its standing army must be within 0.5x-2x of the same
/// faction under the anchor.
///
/// **The scope's other half, standing < field < levy in every reading, did
/// not hold until owner Ruling DE, and not because of G1's rows** (measured
/// 2026-10-25, first run: 90 of 120). The control below forces faction 1 to
/// each of the reference's eight real forms on the same worlds, and they broke
/// the ordering on the same worlds: a faction whose land feeds more than its
/// people (a high `ecological_factor`) was paid a standing army above the
/// field army its levy could concentrate, because the standing budget was
/// linear in the factor (`ECOLOGICAL_ARMY_TERM_SCOPE.md` §2). Ruling DE's
/// term (EA-1) fixed the model, and the ordering is now asserted on every
/// forced reading, G1 and reference alike (160 and 160 of 160, measured). The
/// one-directional guard stays too: no form breaks an ordering its anchor
/// row keeps (since G1-5 the khanate's levy bonus may order it where its
/// anchor is not, which is allowed). The era-band
/// verdict counts are printed, not barred (a form outside its band is a
/// finding, `MILITARY_MANPOWER_SCOPE.md` §1). Ignored: it generates 20
/// worlds.
#[test]
#[ignore = "G1-1 forced readings over 20 generated worlds; run alone with --ignored"]
fn g1_forced_forms_are_ordered_and_near_their_anchor() {
    let (mut n, mut ordered, mut near, mut same_as_anchor) = (0usize, 0usize, 0usize, 0usize);
    let (mut ref_n, mut ref_ordered) = (0usize, 0usize);
    let is_ordered = |m: &Manpower| m.standing_army < m.field_army && m.field_army < m.emergency_mobilization;
    let mut verdicts: std::collections::BTreeMap<(String, &str, &str), usize> = Default::default();
    let (mut lo, mut hi) = (f64::INFINITY, 0.0f64);
    for &(seed, width, factions) in worlds().iter() {
        let (ws, mut civ, gh, p) = generate_world(seed, f64::from(width), factions, GW);
        let saved = civ.faction_roster.0[1].government.clone();
        for &(form, anchor) in G1_FORMS.iter() {
            civ.faction_roster.0[1].government = form.to_string();
            let m = read(&civ, &ws, gh, p.map_width_km, seed, true).rows.swap_remove(0);
            civ.faction_roster.0[1].government = anchor.to_string();
            let a = read(&civ, &ws, gh, p.map_width_km, seed, true).rows.swap_remove(0);
            n += 1;
            assert!(m.standing_army > 0.0, "seed {seed} {width} {factions} {form}: faction 1 has no army");
            if is_ordered(&m) {
                ordered += 1;
            } else {
                println!("G1 unordered: seed {seed} {width} {factions} {form}: {:.0} / {:.0} / {:.0} (anchor {anchor} ordered: {})", m.standing_army, m.field_army, m.emergency_mobilization, is_ordered(&a));
            }
            // One-directional: an appended form may be ordered where its anchor
            // is not (G1-5's khanate levy bonus does exactly that), but must
            // never break an ordering its anchor keeps.
            same_as_anchor += usize::from(is_ordered(&m) || !is_ordered(&a));
            let r = m.standing_army / a.standing_army;
            lo = lo.min(r);
            hi = hi.max(r);
            if (0.5..=2.0).contains(&r) {
                near += 1;
            } else {
                println!("G1 far from anchor: seed {seed} {width} {factions} {form}/{anchor}: {r:.3}");
            }
            *verdicts.entry((form.to_string(), m.era_standing_verdict, m.era_mobilization_verdict)).or_default() += 1;
        }
        // The control: the reference's eight real forms on the same faction.
        for &(form, _) in cartalith_civ::roster::CIV_GOVERNMENTS[1..cartalith_civ::roster::CIV_GOVERNMENTS_REFERENCE_LEN].iter() {
            civ.faction_roster.0[1].government = form.to_string();
            let m = read(&civ, &ws, gh, p.map_width_km, seed, true).rows.swap_remove(0);
            ref_n += 1;
            ref_ordered += usize::from(is_ordered(&m));
        }
        civ.faction_roster.0[1].government = saved;
    }
    println!("G1 forced readings: {n}; ordered {ordered}; no ordering broken that the anchor keeps {same_as_anchor}; within 0.5x-2x of anchor {near} (ratio {lo:.3}..{hi:.3})");
    println!("G1 control, reference forms on the same faction: {ref_n}; ordered {ref_ordered}");
    for ((form, s, mob), c) in verdicts.iter() {
        println!("G1 verdicts {form}: standing {s}, mobilization {mob}: {c}");
    }
    assert_eq!(n, 20 * G1_FORMS.len());
    assert_eq!(ref_n, 20 * 8);
    assert_eq!(same_as_anchor, n, "a G1 row broke an ordering its anchor keeps");
    assert_eq!(near, n, "standing within 0.5x-2x of the anchor row's");
    // Since owner Ruling DE (EA-1) the ordering itself holds on every forced
    // reading, the scope's G1-1 bar 4 as first written. Faction 1 is never
    // empty on these worlds (asserted above: a non-zero standing army), so
    // there is no empty reading to exclude here; `ea0_` counts them apart.
    assert_eq!(ordered, n, "standing < field < levy on every forced G1 reading");
    assert_eq!(ref_ordered, ref_n, "standing < field < levy on every forced reference reading");
}

// ======================================================== EA-0 (Ruling DE)

/// How one faction's reading stands against the model ordering
/// `standing < field < levy` (`ECOLOGICAL_ARMY_TERM_SCOPE.md` §2.2).
///
/// **Empty is its own answer, never a pass and never a failure.** A faction
/// with no population reads `0 / 0 / 0`; `0 < 0` is false, so a plain
/// inequality would call it unordered, and counting it as ordered would
/// encode "no army" as a healthy one (`MISTAKES.md`, never encode "no value"
/// as a plausible value). The ten such factions on the harness worlds are
/// counted separately by every caller.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Order {
    Ordered,
    Unordered,
    Empty,
}

/// [`Order`] for one row. Empty means zero total population, the only way a
/// row reads `0 / 0 / 0` (`civ_military_manpower` absorbs non-finite input to
/// zero, so there is no NaN case to classify; the negated test sends a NaN to
/// `Empty` rather than to a verdict anyway).
fn order_of(m: &Manpower) -> Order {
    #[allow(clippy::neg_cmp_op_on_partial_ord)]
    if !(m.total_population > 0.0) {
        Order::Empty
    } else if m.standing_army < m.field_army && m.field_army < m.emergency_mobilization {
        Order::Ordered
    } else {
        Order::Unordered
    }
}

/// Counts over a set of rows: ordered / unordered / empty, the standing-band
/// verdicts of the non-empty ones (within / above / below), and how many
/// non-empty rows have an ecological factor above 1 (the factions EA-1's term
/// may move; every other one must stay bit-identical).
#[derive(Default, Clone, Copy, PartialEq, Eq, Debug)]
struct Tally {
    ordered: usize,
    unordered: usize,
    empty: usize,
    within: usize,
    above: usize,
    below: usize,
    eco_above_one: usize,
    /// Non-empty rows whose field army is `FIELD_CAP` of the levy (Ruling
    /// DE's cap binding; reported, not barred).
    capped: usize,
}

impl Tally {
    /// Adds one row. Verdicts and the `E > 1` count skip empty rows, so the
    /// verdict totals equal [`Tally::armed`].
    fn add(&mut self, m: &Manpower) {
        match order_of(m) {
            Order::Ordered => self.ordered += 1,
            Order::Unordered => self.unordered += 1,
            Order::Empty => {
                self.empty += 1;
                return;
            }
        }
        match m.era_standing_verdict {
            "within" => self.within += 1,
            "above" => self.above += 1,
            _ => self.below += 1,
        }
        self.eco_above_one += usize::from(m.drivers.ecological_factor > 1.0);
        let share = m.field_army / m.emergency_mobilization;
        self.capped += usize::from((share - cartalith_civ::manpower::FIELD_CAP).abs() < 1e-9);
    }

    /// Adds another tally's counts into this one.
    fn merge(&mut self, o: &Tally) {
        self.ordered += o.ordered;
        self.unordered += o.unordered;
        self.empty += o.empty;
        self.within += o.within;
        self.above += o.above;
        self.below += o.below;
        self.eco_above_one += o.eco_above_one;
        self.capped += o.capped;
    }

    /// Non-empty rows: the population every ordering bar is a share of.
    fn armed(&self) -> usize {
        self.ordered + self.unordered
    }
}

/// EA-0's diagnostic (`ECOLOGICAL_ARMY_TERM_SCOPE.md` §2.3 and §7, Ruling DE),
/// committed as one ignored harness test over the 20 FH-R2 worlds and read
/// through the app's own chain ([`read`]). Three readings per world:
///
/// 1. **Default governments**, every real faction as generated: ordered /
///    unordered / empty, standing verdicts, and one `EA row` line per faction
///    (its `E`, `α`, the three headcounts, and the bits of standing and field)
///    so that two runs on two trees can be diffed faction by faction. That
///    diff is how EA-1's "moved exactly the `E > 1` factions" bar is measured,
///    rather than by a replica of the code it checks.
/// 2. **Forced forms**: faction 1 under each [`G1_FORMS`] form, then each of
///    the reference's eight real forms (the readings
///    [`g1_forced_forms_are_ordered_and_near_their_anchor`] takes).
/// 3. **The ag-tech sweep**: every faction forced to each
///    `cartalith_civ::roster::AG_TECH_LEVELS` row in turn. `E` is world-
///    relative, so it is unchanged when all factions share one row; the sweep
///    therefore varies `α` at the measured geography (§2.3 point 2).
///
/// Every unordered non-empty faction is printed with its government, `E`, `α`
/// and standing/field. The literals asserted at the end are the **measured**
/// counts of the tree they were recorded on, not targets: a change that moves
/// one re-records it with the old value beside the new (`MISTAKES.md`,
/// "Change generated output").
///
/// Recorded 2026-10-25 on the tree before EA-1, twice, because the worlds
/// moved under it. On `d423b13e` they reproduced the scope's §2.2 and §5
/// "current" row exactly (231 / 59 / 10; verdicts 55 / 92 / 143; `E > 1` on
/// 114; 17 worlds; forced 125 and 120 of 160; sweep 290, 231, 235, 201, 165,
/// 127). Ruling DB item 3 (`9b0bec28`, the higher world ceiling, on in the
/// app's `params::defaults()`) then re-generated the harness worlds' terrain;
/// the same measurement on `9b0bec28`, the tree EA-1 is built on, read 226 /
/// 64 / 10, verdicts 59 / 88 / 143, `E > 1` on 112, 15 worlds, forced 132 and
/// 128, sweep 290, 226, 239, 201, 170, 124.
///
/// **RE-BASELINED 2026-10-25 under owner Ruling DE (EA-1).** The literals
/// below are the measurement after the ecological army term, with the
/// `9b0bec28` pre-term value beside each. They are EA-1's bars: every
/// non-empty faction ordered, both forced sets 160 of 160, the empties
/// counted apart. On `50a6fc6d` the sweep had one pre-industrial exception
/// (an `improvedAgrarian` republic, 314159/800/24 faction 21, at `E` 0.973 and
/// the logistics floor 0.150). Any such exception is printed
/// (`EA sweep unordered`) and pinned as measured rather than tuned away.
///
/// **RE-RECORDED 2026-10-25 after owner Rulings DG and DJ** (the VA-6 volcano
/// kinds, `5cfa2997` and `1153bbee`), which re-generated the worlds' terrain
/// and moved these counts without re-recording them (bisected on
/// [`G1_0`]'s manpower column; `ECOLOGICAL_ARMY_TERM_SCOPE.md` §10). The
/// ordering bars are unchanged (290 / 0 / 10; 160 and 160). The verdicts, the
/// `E > 1` count and the cap count moved with the geography. The
/// `improvedAgrarian` exception is gone: the same faction now reads `E` 0.294
/// and is ordered. `industrial` reads 129 of 290; it fails because chain 2 has
/// no industrial term (§10), which is still open.
///
/// Run (alone): `cargo test -p cartalith-godot --lib ea0_ -j 2 -- --ignored --nocapture --test-threads 1`
#[test]
#[ignore = "EA-0 diagnostic over 20 generated worlds; run alone with --ignored"]
fn ea0_ecological_ordering_diagnostic() {
    use cartalith_civ::roster::{AG_TECH_LEVELS, CIV_GOVERNMENTS, CIV_GOVERNMENTS_REFERENCE_LEN};
    let mut default = Tally::default();
    let (mut g1, mut reference) = (Tally::default(), Tally::default());
    let mut sweep = [Tally::default(); 6];
    let mut unordered_worlds: Vec<String> = Vec::new();
    for &(seed, width, factions) in worlds().iter() {
        let (ws, mut civ, gh, p) = generate_world(seed, f64::from(width), factions, GW);
        let base = read(&civ, &ws, gh, p.map_width_km, seed, true);
        assert_eq!(base.rows.len(), factions as usize, "one manpower row per real faction");
        let mut here = Tally::default();
        for (i, m) in base.rows.iter().enumerate() {
            here.add(m);
            let d = &m.drivers;
            println!(
                "EA row {seed} {width} {factions} f{} {:?} E {:.4} a {:.3} standing {:.1} field {:.1} levy {:.1} 0x{:016x} 0x{:016x}",
                i + 1,
                order_of(m),
                d.ecological_factor,
                d.agricultural_labour_ratio,
                m.standing_army,
                m.field_army,
                m.emergency_mobilization,
                m.standing_army.to_bits(),
                m.field_army.to_bits()
            );
            if order_of(m) == Order::Unordered {
                println!(
                    "EA unordered: seed {seed} {width} {factions} f{} ({}): E {:.3} a {:.3} standing/field {:.3}",
                    i + 1,
                    civ.faction_roster.0[i + 1].government,
                    d.ecological_factor,
                    d.agricultural_labour_ratio,
                    m.standing_army / m.field_army
                );
            }
        }
        println!(
            "EA world {seed} {width} {factions}: ordered {} unordered {} empty {}; f1 E {:.3}",
            here.ordered, here.unordered, here.empty, base.rows[0].drivers.ecological_factor
        );
        if here.unordered > 0 {
            unordered_worlds.push(format!("{seed}/{width}/{factions}"));
        }
        default.merge(&here);

        // Forced forms on faction 1, then restored.
        let saved = civ.faction_roster.0[1].government.clone();
        let (mut g1_here, mut ref_here) = (Tally::default(), Tally::default());
        for &(form, _) in G1_FORMS.iter() {
            civ.faction_roster.0[1].government = form.to_string();
            g1_here.add(&read(&civ, &ws, gh, p.map_width_km, seed, true).rows[0]);
        }
        for &(form, _) in CIV_GOVERNMENTS[1..CIV_GOVERNMENTS_REFERENCE_LEN].iter() {
            civ.faction_roster.0[1].government = form.to_string();
            ref_here.add(&read(&civ, &ws, gh, p.map_width_km, seed, true).rows[0]);
        }
        civ.faction_roster.0[1].government = saved;
        println!(
            "EA forced {seed} {width} {factions}: G1 ordered {} of {}, reference ordered {} of {}",
            g1_here.ordered,
            g1_here.armed(),
            ref_here.ordered,
            ref_here.armed()
        );
        g1.merge(&g1_here);
        reference.merge(&ref_here);

        // The ag-tech sweep: every real faction on one row, then restored.
        let saved_tech: Vec<String> = civ.faction_roster.0.iter().map(|e| e.ag_tech.clone()).collect();
        for (ri, row) in AG_TECH_LEVELS.iter().enumerate() {
            for e in civ.faction_roster.0.iter_mut().skip(1) {
                e.ag_tech = row.key.to_string();
            }
            for (i, m) in read(&civ, &ws, gh, p.map_width_km, seed, true).rows.iter().enumerate() {
                sweep[ri].add(m);
                // The pre-industrial rows are where Ruling DE Q4 holds the
                // ordering, so every exception there is printed with its drivers.
                if ri < 4 && order_of(m) == Order::Unordered {
                    let d = &m.drivers;
                    println!(
                        "EA sweep unordered: {} seed {seed} {width} {factions} f{} ({}): E {:.3} s {:.3} L {:.3} standing {:.1} field {:.1} levy {:.1}",
                        row.key,
                        i + 1,
                        civ.faction_roster.0[i + 1].government,
                        d.ecological_factor,
                        d.state_capacity,
                        d.logistics_capacity,
                        m.standing_army,
                        m.field_army,
                        m.emergency_mobilization
                    );
                }
            }
        }
        for (e, t) in civ.faction_roster.0.iter_mut().zip(saved_tech) {
            e.ag_tech = t;
        }
        let back = read(&civ, &ws, gh, p.map_width_km, seed, true);
        assert_eq!(back.manpower, base.manpower, "seed {seed} {width} {factions}: restore");
    }

    println!(
        "EA default governments: ordered {} unordered {} empty {} (non-empty {}); standing verdicts within {} above {} below {}; E > 1 on {}; field capped {}; unordered on {} worlds {:?}",
        default.ordered,
        default.unordered,
        default.empty,
        default.armed(),
        default.within,
        default.above,
        default.below,
        default.eco_above_one,
        default.capped,
        unordered_worlds.len(),
        unordered_worlds
    );
    println!(
        "EA forced: G1 ordered {} of {} (empty {}); reference ordered {} of {} (empty {})",
        g1.ordered,
        g1.armed(),
        g1.empty,
        reference.ordered,
        reference.armed(),
        reference.empty
    );
    for (row, t) in AG_TECH_LEVELS.iter().zip(sweep.iter()) {
        println!(
            "EA sweep {}: ordered {} of {} (empty {}), standing within {}, field capped {}",
            row.key,
            t.ordered,
            t.armed(),
            t.empty,
            t.within,
            t.capped
        );
    }

    // Shape guards first, so a silently empty reading cannot pass the counts.
    assert_eq!(default.armed() + default.empty, 300, "10 worlds x 6 + 10 x 24 factions");
    assert_eq!(g1.armed() + g1.empty, 20 * G1_FORMS.len());
    assert_eq!(reference.armed() + reference.empty, 20 * 8);
    for t in sweep.iter() {
        assert_eq!(t.armed() + t.empty, 300);
    }

    // The measured bar (see the doc for the tree it was recorded on).
    let sweep_ordered: Vec<usize> = sweep.iter().map(|t| t.ordered).collect();
    // Each literal is the post-Ruling-DE measurement; the 9b0bec28 pre-term
    // one is beside it (the d423b13e ones are in the doc).
    assert_eq!(
        (default.ordered, default.unordered, default.empty),
        (290, 0, 10), // before Ruling DE: (226, 64, 10)
        "default governments: ordered / unordered / empty"
    );
    // before Ruling DE: (59, 88, 143); (138, 9, 143) at 50a6fc6d, before Rulings DG/DJ moved the worlds
    assert_eq!((default.within, default.above, default.below), (132, 10, 148), "standing verdicts");
    // Ruling DE does not move E; Rulings DG/DJ's terrain does: 112 at 50a6fc6d
    assert_eq!(default.eco_above_one, 109, "non-empty factions with E > 1"); 
    assert_eq!(unordered_worlds.len(), 0, "worlds with an unordered faction"); // before: 15
    assert_eq!((g1.ordered, g1.armed()), (160, 160), "forced G1 forms"); // before: 132
    assert_eq!((reference.ordered, reference.armed()), (160, 160), "forced reference forms"); // before: 128
    // before Ruling DE: [290, 226, 239, 201, 170, 124]; [.., 289, 264, 127] at 50a6fc6d
    assert_eq!(sweep_ordered, vec![290, 290, 290, 290, 264, 129], "ag-tech sweep, ordered of 290");
    // Where FIELD_CAP binds (0 before the ruling: the share topped out at 0.54;
    // 18 at 50a6fc6d).
    assert_eq!(default.capped, 21, "field armies at FIELD_CAP of the levy");
}
