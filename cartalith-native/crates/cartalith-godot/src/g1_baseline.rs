//! G1 governments: milestone **G1-0's measurement columns** and the bars of
//! the later G1 milestones that need real worlds (`GOVERNMENTS_SCOPE.md` §8,
//! approved by Ruling CZ, 2026-10-25), as ignored tests over the real pipeline.
//!
//! What it is for. G1 appends government forms to
//! `cartalith_civ::roster::CIV_GOVERNMENTS` and rows to `manpower`'s two
//! tables. The scope's three guards (§4.1-§4.3) are meant to make that move
//! **no generated output**: no fresh faction may default to a new form, and
//! the two derivations read only the reference rows. `fh_r2_baseline`'s roster
//! column would catch a leaky default pick, but nothing caught a re-derived
//! `SOLDIER_UPKEEP_BY_BRACKET` or `CITIZEN_MODERNISATION`, which move every
//! faction's manpower while leaving every government key alone. This harness
//! adds the column that does.
//!
//! Columns, per world (each a 64-bit FNV-1a, `fh_r2_baseline::Fnv`):
//!
//! - **governments** -- every faction's `government` key, in roster order, as
//!   `compute_civilisation` seeds them (`FactionEntry::default_for` ->
//!   `civ_default_government`). Government only, so a move here is a default
//!   pick and nothing else.
//! - **manpower** -- for every real faction, in roster order, the app's own
//!   reading (`MilWorld::manpower_rows_of`, the body `WorldGen`'s CIVIL ▸
//!   Military summary runs): standing army, professional core, levy
//!   (emergency mobilization), field army, field and levy durations, citizen
//!   fraction, each by `f64::to_bits`; then the era name and both verdicts as
//!   strings. A one-ulp change to any of them moves the hash.
//!
//! The aggregates are taken **with** the resource passes, as
//! `aggregates_with_walls` (the CIVIL ▸ Military path) takes them. The first
//! world also re-reads them without, and asserts the manpower hash is the
//! same: `aggregates_of`'s doc claims the resource passes change only the
//! trade half, and this checks that claim rather than relying on it.
//!
//! Worlds: `fh_r2_baseline`'s twenty (five seeds x {800 km plain, 40 075 km
//! wrapped} x {6, 24 factions}, grid 384 wide), generated by its
//! `generate_world`, so the roster column can be checked against that
//! harness's literals (bar 3).
//!
//! What it must never do: re-record its literals in passing. `G1_0` is the
//! pre-G1 baseline; a G1 stage that moves it has failed its bar, and only an
//! owner-ruled change to generated output may re-record it, with the old value
//! beside the new (`MISTAKES.md`, "Change generated output").
//!
//! Run (alone, one cargo at a time):
//! `cargo test -p cartalith-godot --lib g1_baseline -j 2 -- --ignored --nocapture --test-threads 1`

